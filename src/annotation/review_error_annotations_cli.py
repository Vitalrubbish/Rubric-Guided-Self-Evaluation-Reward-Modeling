#!/usr/bin/env python3
"""Interactive terminal reviewer for error attribution annotations.

This is intentionally dependency-free so it works inside a VSCode Remote SSH
terminal. It loads the review set generated by build_error_annotation_review_set.py
and saves one JSONL annotation record per response id after every completed item.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
from pathlib import Path
from typing import Any


DEFAULT_LABELS = [
    "syntax_parseability_truncation",
    "interface_name_signature_mismatch",
    "runtime_api_type_misuse",
    "timeout_or_complexity",
    "truncation_or_overgeneration",
    "output_type_or_container_shape",
    "numeric_formula_arithmetic_error",
    "sequence_collection_transformation_error",
    "predicate_branch_condition_error",
    "string_regex_pattern_logic",
    "edge_case_handling",
    "logic_other",
    "public_contract_unclear",
    "not_a_failure",
]

CONFIDENCE = {
    "h": "high",
    "m": "medium",
    "l": "low",
}


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows = []
    if not path.exists():
        return rows
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")


def clear() -> None:
    if sys.stdout.isatty():
        os.system("clear")


def color(text: str, code: str) -> str:
    if not sys.stdout.isatty():
        return text
    return f"\033[{code}m{text}\033[0m"


def title(text: str) -> str:
    return color(text, "1;36")


def warn(text: str) -> str:
    return color(text, "1;33")


def ok(text: str) -> str:
    return color(text, "1;32")


def bad(text: str) -> str:
    return color(text, "1;31")


def terminal_width() -> int:
    return shutil.get_terminal_size((120, 24)).columns


def wrap(text: Any, limit: int | None = None) -> str:
    width = max(60, min(terminal_width(), 140))
    limit = limit or 1200
    raw = str(text or "").strip()
    if len(raw) > limit:
        raw = raw[: limit - 24].rstrip() + "\n... [truncated]"
    lines = []
    for paragraph in raw.splitlines() or [""]:
        if not paragraph.strip():
            lines.append("")
            continue
        current = ""
        for part in paragraph.split(" "):
            if len(current) + len(part) + 1 > width:
                lines.append(current.rstrip())
                current = ""
            current += part + " "
        if current:
            lines.append(current.rstrip())
    return "\n".join(lines)


def code_block(text: Any, limit: int = 2200) -> str:
    raw = str(text or "").rstrip()
    if len(raw) > limit:
        raw = raw[: limit - 24].rstrip() + "\n# ... [truncated]"
    return raw


def one_line(text: Any, limit: int = 160) -> str:
    value = re.sub(r"\s+", " ", str(text or "").strip())
    if len(value) > limit:
        return value[: limit - 3].rstrip() + "..."
    return value


def load_annotations(path: Path) -> dict[str, dict[str, Any]]:
    records = {}
    for row in read_jsonl(path):
        rid = str(row.get("response_id") or "")
        if rid:
            records[rid] = row
    return records


def save_annotations(path: Path, annotations: dict[str, dict[str, Any]], item_order: list[str]) -> None:
    rows = [annotations[rid] for rid in item_order if rid in annotations]
    write_jsonl(path, rows)


def default_annotation(item: dict[str, Any]) -> dict[str, Any]:
    return {
        "response_id": item["response_id"],
        "current_label": item.get("current_label"),
        "provisional_label": item.get("provisional_label"),
        "provisional_confidence": item.get("provisional_confidence"),
        "human_primary_label": None,
        "human_secondary_label": None,
        "confidence": None,
        "evidence": "",
        "notes": "",
    }


def load_label_options(review_items: Path, labels_file: Path | None = None) -> list[str]:
    if labels_file:
        source = json.loads(labels_file.read_text(encoding="utf-8"))
        if isinstance(source, list):
            return [str(item) for item in source]
        if isinstance(source, dict) and isinstance(source.get("label_options"), list):
            return [str(item) for item in source["label_options"]]
    summary = review_items.parent / "summary.json"
    if summary.exists():
        source = json.loads(summary.read_text(encoding="utf-8"))
        labels = source.get("label_options")
        if isinstance(labels, list) and labels:
            return [str(item) for item in labels]
    return list(DEFAULT_LABELS)


def label_menu(labels: list[str]) -> str:
    lines = []
    for index, label in enumerate(labels, start=1):
        lines.append(f"{index:2d}. {label}")
    return "\n".join(lines)


def select_label(prompt: str, labels: list[str], allow_empty: bool = False) -> str | None:
    while True:
        value = input(prompt).strip()
        if allow_empty and not value:
            return None
        if value.isdigit():
            index = int(value)
            if 1 <= index <= len(labels):
                return labels[index - 1]
        matches = [label for label in labels if label.startswith(value)]
        if len(matches) == 1:
            return matches[0]
        print(bad("Invalid label. Type a number from the label menu or a unique prefix."))


def multiline_input(prompt: str, existing: str = "") -> str:
    print(prompt)
    if existing:
        print(warn(f"Current: {existing}"))
    print("Enter text. Submit an empty line to finish.")
    lines = []
    while True:
        line = input("> ")
        if line == "":
            break
        lines.append(line)
    return "\n".join(lines).strip() if lines else existing


def optional_line_input(prompt: str, existing: str = "") -> str:
    suffix = f" [{existing}]" if existing else " [optional, Enter to skip]"
    value = input(f"{prompt}{suffix}: ").strip()
    return value if value else existing


def status_line(annotation: dict[str, Any] | None) -> str:
    if not annotation or not annotation.get("human_primary_label"):
        return warn("unreviewed")
    label = annotation.get("human_primary_label")
    confidence = annotation.get("confidence")
    return ok(f"{label} / {confidence}")


def show_item(item: dict[str, Any], annotation: dict[str, Any] | None, mode: str = "normal") -> None:
    clear()
    print(title(f"Item {item['review_index']:03d}: {item['response_id']}"))
    print(f"Status: {status_line(annotation)}")
    print()
    print(f"Current label: {color(str(item.get('current_label')), '1;35')}")
    print(f"Provisional:   {color(str(item.get('provisional_label') or ''), '1;34')} ({item.get('provisional_confidence') or ''})")
    print(f"Failure type:  {item.get('failure_type')}    Error pattern: {item.get('error_pattern')}")
    print(f"IO mode:       {item.get('io_mode')}    Sampling: {item.get('sampling_reason')}")
    print()
    print(title("Verifier summary"))
    print(json.dumps(item.get("verifier_summary") or {}, ensure_ascii=False, indent=2))
    print()
    print(title("Current LLM summary"))
    print(wrap(item.get("llm_summary"), 800))
    print()
    if item.get("provisional_reason"):
        print(title("Provisional rationale"))
        print(wrap(item.get("provisional_reason"), 800))
        print()
    print(title("Task"))
    print(wrap(item.get("task"), 1800 if mode == "normal" else 6000))
    print()
    print(title("Extracted code"))
    print(code_block(item.get("extracted_code"), 2200 if mode == "normal" else 6000))
    if mode == "full":
        print()
        print(title("Generated response"))
        print(code_block(item.get("generated_code"), 6000))
    print()
    print(title("Commands"))
    print("[a] annotate  [n] next  [p] previous  [f] full/short  [l] labels  [j] jump  [q] quit")


def annotate_item(
    item: dict[str, Any],
    annotations: dict[str, dict[str, Any]],
    labels: list[str],
    detailed: bool = False,
    require_evidence: bool = False,
) -> dict[str, Any]:
    current = annotations.get(item["response_id"], default_annotation(item))

    print()
    print(title("Controlled labels"))
    print(label_menu(labels))
    if not current.get("human_primary_label"):
        current["human_primary_label"] = item.get("provisional_label") or item.get("current_label")
        if current.get("human_primary_label"):
            print(ok(f"Default primary label: {current['human_primary_label']}"))
    current["human_primary_label"] = select_label(
        f"Primary label [{current.get('human_primary_label') or 'none'}]: ",
        labels,
        allow_empty=bool(current.get("human_primary_label")),
    ) or current.get("human_primary_label")
    current["human_secondary_label"] = select_label(
        f"Secondary label optional [{current.get('human_secondary_label') or 'none'}]: ",
        labels,
        allow_empty=True,
    )

    print()
    print(title("Confidence"))
    print("h=high, m=medium, l=low")
    if not current.get("confidence"):
        current["confidence"] = item.get("provisional_confidence")
    while True:
        value = input(f"Confidence [{current.get('confidence') or 'none'}]: ").strip().lower()
        if not value and current.get("confidence"):
            confidence = current["confidence"]
            break
        if value in CONFIDENCE:
            confidence = CONFIDENCE[value]
            break
        print(bad("Invalid confidence."))
    current["confidence"] = confidence

    if detailed:
        current["evidence"] = multiline_input("Evidence grounded in public task/code:", current.get("evidence") or "")
        current["notes"] = multiline_input("Optional notes:", current.get("notes") or "")
    else:
        current["evidence"] = optional_line_input(
            "Short evidence, only if useful",
            current.get("evidence") or "",
        )
        current["notes"] = optional_line_input("Notes", current.get("notes") or "")
    if require_evidence and not str(current.get("evidence") or "").strip():
        current["evidence"] = optional_line_input("Evidence is required for this run", "")
    annotations[item["response_id"]] = current
    return current


def filtered_items(items: list[dict[str, Any]], category: str | None) -> list[dict[str, Any]]:
    if not category:
        return items
    return [item for item in items if item.get("current_label") == category]


def print_summary(items: list[dict[str, Any]], annotations: dict[str, dict[str, Any]]) -> None:
    reviewed = sum(1 for item in items if item["response_id"] in annotations and annotations[item["response_id"]].get("human_primary_label"))
    print(f"Items: {len(items)}")
    print(f"Reviewed: {reviewed}")
    counts: dict[str, int] = {}
    for item in items:
        counts[item.get("current_label") or "unknown"] = counts.get(item.get("current_label") or "unknown", 0) + 1
    for label, count in sorted(counts.items()):
        print(f"{label}: {count}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Review error attribution labels in a terminal.")
    parser.add_argument("--review-items", type=Path, default=Path("data/annotation/apps_simple_error_review_v1/review_items.jsonl"))
    parser.add_argument("--annotations", type=Path, default=Path("data/annotation/apps_simple_error_review_v1/annotations_working.jsonl"))
    parser.add_argument("--labels-file", type=Path, help="Optional JSON list or summary JSON containing label_options.")
    parser.add_argument("--category", help="Only review items with this current_label.")
    parser.add_argument("--summary", action="store_true", help="Print review progress and exit.")
    parser.add_argument("--detailed", action="store_true", help="Use multiline evidence and notes prompts.")
    parser.add_argument("--require-evidence", action="store_true", help="Require a non-empty evidence field.")
    args = parser.parse_args()

    items = filtered_items(read_jsonl(args.review_items), args.category)
    if not items:
        raise SystemExit("No review items found.")
    annotations = load_annotations(args.annotations)
    labels = load_label_options(args.review_items, args.labels_file)
    item_order = [str(item["response_id"]) for item in read_jsonl(args.review_items)]

    if args.summary:
        print_summary(items, annotations)
        return

    index = 0
    full = False
    while 0 <= index < len(items):
        item = items[index]
        annotation = annotations.get(item["response_id"])
        show_item(item, annotation, mode="full" if full else "normal")
        command = input("> ").strip().lower()
        if command in {"", "n"}:
            index += 1
        elif command == "p":
            index = max(0, index - 1)
        elif command == "f":
            full = not full
        elif command == "l":
            print(label_menu(labels))
            input("Press Enter to continue...")
        elif command == "a":
            annotate_item(item, annotations, labels, detailed=args.detailed, require_evidence=args.require_evidence)
            save_annotations(args.annotations, annotations, item_order)
            print(ok(f"Saved to {args.annotations}"))
            input("Press Enter for next item...")
            index += 1
        elif command == "j":
            value = input(f"Jump to item number 1-{len(items)}: ").strip()
            if value.isdigit():
                index = max(0, min(len(items) - 1, int(value) - 1))
        elif command == "q":
            break
        else:
            print(bad("Unknown command."))
            input("Press Enter to continue...")

    save_annotations(args.annotations, annotations, item_order)
    print(ok(f"Annotation progress saved to {args.annotations}"))


if __name__ == "__main__":
    main()
